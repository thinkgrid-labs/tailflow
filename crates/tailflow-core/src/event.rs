//! Versioned, normalized observability events.
//!
//! [`LogRecord`] is a text line. An [`ObservabilityEvent`] is the general
//! envelope that runtime logs, collector lifecycle, and (from M2) coding-agent
//! activity share. Runtime logs keep flowing as `LogRecord` through the live
//! bus; [`ObservabilityEvent::from_log_record`] is the one-way bridge into the
//! durable store.
//!
//! Contract rules:
//!
//! - `schema_version` is bumped for any incompatible change to the envelope.
//!   Readers must reject versions they do not know rather than guess.
//! - `event_type` must be in [`EVENT_TYPES`]. An unknown type is an error, not
//!   a silent pass-through, so a misspelled `file.modifed` never looks like
//!   "no file changes".
//! - Unknown envelope fields are rejected on deserialization
//!   (`deny_unknown_fields`). Extensions go in `attributes`.
//! - `provenance` says how the fact was obtained. Relationship fields
//!   (`parent_operation_id`, `session_id`) are *as reported* by that source.
//!   Anything TailFlow infers must be written under an `inferred.` attribute
//!   prefix, never into these fields.

use crate::{LogLevel, LogRecord};
use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use serde_json::{Map, Value};
use std::fmt;

/// Current envelope version.
pub const EVENT_SCHEMA_VERSION: u16 = 1;

/// Bounds enforced by [`ObservabilityEvent::validate`].
pub const MAX_ATTRIBUTES: usize = 64;
pub const MAX_ATTRIBUTE_KEY_LEN: usize = 64;
/// Serialized size cap for the whole `attributes` object.
pub const MAX_ATTRIBUTES_BYTES: usize = 16 * 1024;
pub const MAX_ID_LEN: usize = 256;
pub const MAX_PATH_LEN: usize = 4096;
/// Messages longer than this are truncated (on a char boundary) before storage.
pub const MAX_MESSAGE_BYTES: usize = 16 * 1024;
/// Optional payloads longer than this are truncated before storage.
pub const MAX_PAYLOAD_BYTES: usize = 256 * 1024;

/// How an event was obtained. Distinguishes observed facts from claims.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum Provenance {
    /// The agent (or its hook) said it did this. Not independently verified.
    AgentReported,
    /// Seen by a filesystem watcher. Says nothing about *who* changed the file.
    FilesystemObserved,
    /// Captured from a running process, container, file tail, or stdin.
    RuntimeObserved,
    /// Generated by TailFlow itself (collector lifecycle, loss markers).
    SystemObserved,
}

impl Provenance {
    pub fn as_str(self) -> &'static str {
        match self {
            Provenance::AgentReported => "agent_reported",
            Provenance::FilesystemObserved => "filesystem_observed",
            Provenance::RuntimeObserved => "runtime_observed",
            Provenance::SystemObserved => "system_observed",
        }
    }

    pub fn parse(s: &str) -> Option<Self> {
        match s {
            "agent_reported" => Some(Provenance::AgentReported),
            "filesystem_observed" => Some(Provenance::FilesystemObserved),
            "runtime_observed" => Some(Provenance::RuntimeObserved),
            "system_observed" => Some(Provenance::SystemObserved),
            _ => None,
        }
    }
}

/// Outcome of an operation-like event.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum EventStatus {
    Started,
    Succeeded,
    Failed,
    Cancelled,
}

impl EventStatus {
    pub fn as_str(self) -> &'static str {
        match self {
            EventStatus::Started => "started",
            EventStatus::Succeeded => "succeeded",
            EventStatus::Failed => "failed",
            EventStatus::Cancelled => "cancelled",
        }
    }

    pub fn parse(s: &str) -> Option<Self> {
        match s {
            "started" => Some(EventStatus::Started),
            "succeeded" => Some(EventStatus::Succeeded),
            "failed" => Some(EventStatus::Failed),
            "cancelled" => Some(EventStatus::Cancelled),
            _ => None,
        }
    }
}

/// One entry of the event-type catalog.
#[derive(Debug, Clone, Copy)]
pub struct EventTypeSpec {
    pub name: &'static str,
    /// Provenance a well-behaved producer of this type normally has.
    pub typical_provenance: Provenance,
    /// Implemented by a collector in this release (`false` = schema only).
    pub collected: bool,
    pub description: &'static str,
}

const fn spec(
    name: &'static str,
    typical_provenance: Provenance,
    collected: bool,
    description: &'static str,
) -> EventTypeSpec {
    EventTypeSpec {
        name,
        typical_provenance,
        collected,
        description,
    }
}

